/**
 * Writes `src/routes/styles.css` — every style's tokens, scoped to a
 * `data-style` attribute, so the docs site can preview one style inside a page
 * drawn in another.
 *
 * This is a **docs-only** file. The package still ships one global `theme.css`
 * per style, and an app still imports exactly one: `--color-brand` cannot hold
 * two values on `:root`. What makes the scoped version work is that Tailwind
 * compiles `bg-brand` to `background-color: var(--color-brand)`, so overriding
 * the variable on an ancestor is enough — every utility inside follows.
 *
 * It is generated rather than hand-kept for the obvious reason: a second copy
 * of eight palettes would drift from the first within a week.
 *
 * Run with `--check` to fail instead of writing.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { STYLES } from './catalogue.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');

/** The body of the first `<selector> { … }` block, assuming no nesting. */
function blockBody(css, selector) {
	const start = css.indexOf(selector);
	if (start === -1) return null;
	const open = css.indexOf('{', start);
	const close = css.indexOf('}', open);
	if (open === -1 || close === -1) return null;
	return css.slice(open + 1, close);
}

/**
 * Custom properties only. `color-scheme` is deliberately dropped: it belongs to
 * the whole document, and setting it on a preview box would repaint the
 * surrounding page's form controls.
 *
 * Comments come out *before* the split on `;`, not after — prose contains
 * semicolons, and splitting first tears a comment in half, which then hides
 * whatever declaration follows it.
 */
function customProperties(body) {
	if (!body) return [];
	return body
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.split(';')
		.map((line) => line.trim())
		.filter((line) => line.startsWith('--'))
		.map((line) => `${line.replace(/\s+/g, ' ')};`);
}

const indent = (lines, depth) => lines.map((line) => `${'\t'.repeat(depth)}${line}`).join('\n');

let out = `/*
 * Generated by \`bun run scoped\` — do not edit.
 *
 * Each style's tokens, scoped to \`[data-style]\` so a preview box can render
 * one style inside a page drawn in another. Docs only; see
 * scripts/generate-scoped-css.mjs for why this is not part of the package.
 */
`;

let baseline = null;

for (const style of STYLES) {
	const css = await readFile(
		new URL(`src/lib/styles/${style.name}/theme.css`, `file://${root}`),
		'utf8'
	);

	const light = customProperties(blockBody(css, '@theme'));
	const dark = customProperties(blockBody(css, '\n.dark'));

	if (light.length === 0) {
		console.error(`${style.name}/theme.css has no @theme block`);
		process.exit(1);
	}

	// The token names are the contract between styles, so a style that quietly
	// drops one would leave components reading an undefined variable. Cheapest
	// place to catch it is here, where every palette is already parsed.
	const names = light.map((line) => line.split(':')[0]);
	if (!baseline) baseline = { style: style.name, names };
	else {
		const missing = baseline.names.filter((n) => !names.includes(n));
		const extra = names.filter((n) => !baseline.names.includes(n));
		if (missing.length || extra.length) {
			console.error(`${style.name}/theme.css does not match ${baseline.style}:`);
			if (missing.length) console.error(`  missing: ${missing.join(', ')}`);
			if (extra.length) console.error(`  extra:   ${extra.join(', ')}`);
			process.exit(1);
		}
	}

	const scope = `[data-style='${style.name}']`;

	out += `\n/* --- ${style.name} --- */\n`;
	out += `${scope} {\n${indent(light, 1)}\n}\n`;

	if (dark.length) {
		// Two selectors each, because the scope sits in two places: on <html>
		// for a whole page, and on a box inside one for a single preview. The
		// first case is a compound selector — `.dark` is on the same element —
		// and the second needs a descendant combinator.
		out += `\n.dark${scope},\n.dark ${scope} {\n${indent(dark, 1)}\n}\n`;
		out += `\n@media (prefers-color-scheme: dark) {\n\t:root:not(.light)${scope},\n\t:root:not(.light) ${scope} {\n${indent(dark, 2)}\n\t}\n}\n`;
	}
}

const path = new URL('src/routes/styles.css', `file://${root}`);

let current = '';
try {
	current = await readFile(path, 'utf8');
} catch {
	/* first run */
}

if (current === out) {
	console.log(`scoped tokens up to date (${STYLES.length} styles)`);
	process.exit(0);
}

if (check) {
	console.error('src/routes/styles.css is stale — run `bun run scoped`');
	process.exit(1);
}

await writeFile(path, out);
console.log(`scoped tokens written (${STYLES.length} styles)`);
